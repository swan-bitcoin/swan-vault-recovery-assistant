fn get_blockchain(
  network: Network,
  electrum: Option<String>,
) -> Result<ElectrumBlockchain, TempuraError> {
  let connection = match electrum {
    Some(electrum) => electrum,
    None => match network {
      Network::Testnet => "electrum.blockstream.info:60001".to_string(),
      Network::Bitcoin => "blockstream.info:110".to_string(),
      Network::Regtest => "localhost:50021".to_string(),
      _ => {
        return Err(TempuraError::new(
          TempuraErrorType::NetworkError,
          "You must specify an electrum server for this network",
        ))
      }
    },
  };

  let client = resolve!(Client::new(&connection), TempuraErrorType::ClientError);
  Ok(ElectrumBlockchain::from(client))
}

fn get_hwi() -> Result<Command, TempuraError> {
  let hwi_path = hwi_path();

  #[allow(unused_mut)]
  let mut command = Command::new(&hwi_path);
  #[cfg(target_os = "windows")]
  {
    const COMMAND_FLAG_CREATE_NO_WINDOW: u32 = 0x08000000;
    command.creation_flags(COMMAND_FLAG_CREATE_NO_WINDOW);
  }
  Ok(command)
}

fn get_wallet(
  network: Network,
  descriptors: Descriptors,
) -> Result<bdk::Wallet<MemoryDatabase>, TempuraError> {
  let secp = Secp256k1::new();
  let network: bdk::bitcoin::Network = network.into();

  // start by resolving the provided required and optional descriptor strings into wallet descriptors
  let mut receive = resolve!(
    descriptors.receive.into_wallet_descriptor(&secp, network),
    TempuraErrorType::DescriptorError(Some(DescriptorType::Receive))
  );

  let mut change = match descriptors.change {
    Some(change) => Some(resolve!(
      change.into_wallet_descriptor(&secp, network),
      TempuraErrorType::DescriptorError(Some(DescriptorType::Change))
    )),
    None => None,
  };

  // don't allow multipath descriptors for change
  if let Some((ref change_desc, _)) = change {
    if change_desc.is_multipath() {
      return Err(TempuraError::new(
            TempuraErrorType::DescriptorError(Some(DescriptorType::Change)),
            "A change descriptor must not be a multipath descriptor. Use this as a receive descriptor instead.",
        ));
    }
  }

  // BDK does not currently support multipath wallet descriptors.
  // split the multipath descriptor into receive and change descriptors if necessary
  if receive.0.is_multipath() {
    let paths = resolve!(
      receive.0.clone().into_single_descriptors(),
      TempuraErrorType::DescriptorError(Some(DescriptorType::Multipath))
    );
    if paths.len() == 0 || paths.len() > 2 {
      return Err(TempuraError::new(
        TempuraErrorType::DescriptorError(Some(DescriptorType::Multipath)),
        "A multipath descriptor must have either one or two paths",
      ));
    }

    receive = resolve!(
      paths[0].clone().into_wallet_descriptor(&secp, network),
      TempuraErrorType::DescriptorError(Some(DescriptorType::Multipath))
    );

    change = match (change, paths.get(1)) {
      (None, Some(path)) => Some(resolve!(
        path.clone().into_wallet_descriptor(&secp, network),
        TempuraErrorType::DescriptorError(Some(DescriptorType::Multipath))
      )),
      (Some(change), _) => Some(change),
      (None, None) => None,
    };
  };

  if change.is_none() && receive.0.has_wildcard() && descriptors.auto_change {
    let receive_str = receive.0.to_string();
    let change_str = receive_str.replace("/0/*", "/1/*");
    let change_str = match change_str.rfind("#") {
      Some(i) => {
        let (change_str, _) = change_str.split_at(i);
        change_str.to_string()
      }
      None => change_str,
    };
    change = match change_str == receive_str {
      true => None,
      false => Some(resolve!(
        change_str.into_wallet_descriptor(&secp, network),
        TempuraErrorType::DescriptorError(Some(DescriptorType::Change))
      )),
    }
  };

  Ok(resolve!(
    bdk::Wallet::new(
      receive,
      change,
      network,
      bdk::database::MemoryDatabase::default()
    ),
    TempuraErrorType::WalletError
  ))
}

/**
 * some expected locations for the hwi executable will not be found when searching the system PATH.
 *
 * this function will attempt to find the hwi executable in the following locations, by priority:
 *   - the TEMPURA_HWI_PATH environment variable, if specified
 *   - the directory where the binary is running from, or current directory
 *   - the CARGO_TARGET_DIR environment variable, if specified
 */
fn hwi_path() -> String {
  let mut paths: Vec<String> = Vec::new();
  if let Ok(path) = std::env::var("CARGO_TARGET_DIR") {
    paths.push(path);
  }

  let mut exe_parent_path: String = String::from(".");
  if let Ok(exe_path) = std::env::current_exe() {
    if let Some(parent_dir) = exe_path.parent() {
      exe_parent_path = parent_dir.to_string_lossy().into_owned();
    }
  }
  paths.insert(0, exe_parent_path);

  if let Ok(path) = std::env::var("TEMPURA_HWI_PATH") {
    paths.insert(0, path);
  }

  // search each directory for the executable
  let hwi_name = if cfg!(windows) { "hwi.exe" } else { "hwi" };
  let hwi_path = paths
    .iter()
    .map(|dir| std::path::Path::new(dir).join(hwi_name))
    .find(|path| {
      path.exists()
        && std::fs::metadata(path)
          .map(|meta| meta.is_file())
          .unwrap_or(false)
    });

  if let Some(hwi_path) = hwi_path {
    return hwi_path.to_string_lossy().into_owned();
  }

  // let the system try to find it in PATH, '.exe' not necessary.
  String::from("hwi")
}

